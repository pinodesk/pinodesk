create table if not exists menu (
	id bigint not null auto_increment,
	created_at timestamp not null default current_timestamp,
	updated_at timestamp not null default current_timestamp on update current_timestamp,
	deleted_at timestamp,
	parent_menu_id bigint,
	language char(2) not null,
	code char(4) not null,
	name varchar(64) not null,
	primary key (id),
	index idx_menu__deleted_at (deleted_at),
	index idx_menu__code (code),
	index idx_menu__code__deleted_at (code, deleted_at),
	index idx_menu__language__code (language, code),
	index idx_menu__language__code__deleted_at (language, code, deleted_at)
);

